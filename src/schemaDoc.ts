// Export the tables shown in an ER diagram as SQL DDL or as schema docs
// (Markdown / HTML). Pure — no DOM, no React.
//
//  * DDL: CREATE TABLE for each table, parents before children so the inline
//    FOREIGN KEYs resolve. Tables caught in an FK cycle get those FKs as
//    ALTER TABLE … ADD after every table exists (SQLite keeps them inline —
//    it can't ALTER-add a constraint and doesn't check FKs at CREATE time).
//  * Docs: one section per table — columns (type, null, default, PK/FK),
//    foreign keys, indexes, and which tables point at it.

import {
  buildCreate,
  designerFromSchema,
  fkClause,
  fkValid,
  qualified,
  type ForeignKey,
  type TableSchemaInfo,
} from "./ddl";

export interface DocEdge {
  from: string;
  fromCol: string;
  to: string;
  toCol: string;
  guess?: boolean;
}

/** Match an FK's referenced table to a listed name (exact, then last dotted segment). */
function resolver(names: string[]): (ref: string) => string | null {
  const byLower = new Map(names.map((n) => [n.toLowerCase(), n]));
  return (ref) => {
    const hit = byLower.get(ref.toLowerCase());
    if (hit) return hit;
    const tail = ref.split(".").pop()!.toLowerCase();
    const hits = names.filter((n) => n.split(".").pop()!.toLowerCase() === tail);
    return hits.length === 1 ? hits[0] : null;
  };
}

/** Parents first (Kahn's algorithm, ties kept in the given order); a cycle is
 *  broken at the table the rest of it waits on most. */
export function orderForCreate(names: string[], schemas: Map<string, TableSchemaInfo>): string[] {
  const res = resolver(names);
  const deps = new Map<string, Set<string>>();
  for (const n of names) {
    const d = new Set<string>();
    for (const f of schemas.get(n)?.foreignKeys ?? []) {
      const r = res(f.refTable);
      if (r && r !== n) d.add(r);
    }
    deps.set(n, d);
  }
  const out: string[] = [];
  const done = new Set<string>();
  const unmet = (n: string) => [...deps.get(n)!].filter((d) => !done.has(d)).length;
  while (out.length < names.length) {
    let progress = false;
    for (const n of names) {
      if (!done.has(n) && unmet(n) === 0) {
        out.push(n);
        done.add(n);
        progress = true;
      }
    }
    if (progress) continue;
    // Stuck on a cycle: break it at the table the most pending tables wait on
    // (fewest unmet parents first), so its children can follow straight after.
    const rest = names.filter((n) => !done.has(n));
    const waitedOn = (n: string) => rest.filter((m) => deps.get(m)!.has(n)).length;
    rest.sort((a, b) => unmet(a) - unmet(b) || waitedOn(b) - waitedOn(a));
    out.push(rest[0]);
    done.add(rest[0]);
  }
  return out;
}

export function buildSchemaDdl(
  engine: string,
  db: string,
  names: string[],
  schemas: Map<string, TableSchemaInfo>,
  when = new Date(),
): string {
  const e = engine.toLowerCase();
  const sqlite = e === "sqlite";
  const order = orderForCreate(
    names.filter((n) => schemas.has(n)),
    schemas,
  );
  const res = resolver(order);
  const created = new Set<string>();
  const deferred: { table: string; fk: ForeignKey }[] = [];
  const out: string[] = [
    `-- ${order.length} table${order.length === 1 ? "" : "s"} from ${db || "database"} (${engine})`,
    `-- Generated by BalauDeck on ${when.toISOString().slice(0, 19).replace("T", " ")}`,
    "",
  ];
  for (const n of order) {
    const d = designerFromSchema(db, n, schemas.get(n)!);
    if (!sqlite) {
      const inline: ForeignKey[] = [];
      for (const f of d.fks) {
        const r = res(f.refTable);
        // Parent not created yet (a cycle) → add it once every table exists.
        if (r && r !== n && !created.has(r)) deferred.push({ table: n, fk: f });
        else inline.push(f);
      }
      d.fks = inline;
    }
    for (const s of buildCreate(engine, d)) out.push(s + ";", "");
    created.add(n);
  }
  if (deferred.length) {
    out.push("-- Foreign keys between tables that reference each other");
    for (const { table, fk } of deferred.filter((x) => fkValid(x.fk))) {
      out.push(`ALTER TABLE ${qualified(engine, db, table)} ADD ${fkClause(engine, fk)};`);
    }
    out.push("");
  }
  return out.join("\n");
}

// ---- docs ------------------------------------------------------------------------

function typeOf(c: TableSchemaInfo["columns"][number]): string {
  const t = c.dataType;
  return c.length && !/\(/.test(t) ? `${t}(${c.length})` : t;
}

interface DocTable {
  name: string;
  columns: { name: string; type: string; nullable: boolean; def: string; key: string; refs: string }[];
  fks: { name: string; cols: string; ref: string; rules: string; guess: boolean }[];
  indexes: { name: string; cols: string; unique: boolean }[];
  referencedBy: string[];
}

function docModel(names: string[], schemas: Map<string, TableSchemaInfo>, edges: DocEdge[]): DocTable[] {
  const list = names.filter((n) => schemas.has(n));
  return list.map((n) => {
    const s = schemas.get(n)!;
    const out = edges.filter((x) => x.from === n);
    const refOf = new Map(s.foreignKeys.map((f) => [f.column, `${f.refTable}.${f.refColumn}`]));
    for (const x of out) if (!refOf.has(x.fromCol)) refOf.set(x.fromCol, `${x.to}.${x.toCol}`);
    const guessCols = new Set(out.filter((x) => x.guess).map((x) => x.fromCol));
    const fkCols = new Set(s.foreignKeys.map((f) => f.column));
    return {
      name: n,
      columns: s.columns.map((c) => ({
        name: c.name,
        type: typeOf(c),
        nullable: c.nullable,
        def: c.autoIncrement ? "auto increment" : c.default,
        key: [c.pk ? "PK" : "", fkCols.has(c.name) ? "FK" : guessCols.has(c.name) ? "FK?" : ""].filter(Boolean).join(", "),
        refs: refOf.get(c.name) ?? "",
      })),
      fks: [
        ...s.foreignKeys.map((f) => ({
          name: f.name,
          cols: f.column,
          ref: `${f.refTable}.${f.refColumn}`,
          rules: [f.onDelete && `ON DELETE ${f.onDelete}`, f.onUpdate && `ON UPDATE ${f.onUpdate}`].filter(Boolean).join(", "),
          guess: false,
        })),
        ...out
          .filter((x) => x.guess)
          .map((x) => ({ name: "", cols: x.fromCol, ref: `${x.to}.${x.toCol}`, rules: "guessed from the column name", guess: true })),
      ],
      indexes: s.indexes.map((x) => ({ name: x.name, cols: x.columns.join(", "), unique: x.unique })),
      referencedBy: [...new Set(edges.filter((x) => x.to === n && x.from !== n).map((x) => x.from))].sort(),
    };
  });
}

const mdCell = (s: string) => (s === "" ? "" : s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " "));
const mdCode = (s: string) => (s === "" ? "" : "`" + s.replace(/`/g, "'") + "`");
const anchor = (s: string) => s.toLowerCase().replace(/[^\w]+/g, "-").replace(/^-|-$/g, "");

export function buildSchemaMarkdown(
  db: string,
  engine: string,
  names: string[],
  schemas: Map<string, TableSchemaInfo>,
  edges: DocEdge[],
  when = new Date(),
): string {
  const tables = docModel(names, schemas, edges);
  const L: string[] = [];
  L.push(`# ${db || "Database"} — schema`, "");
  L.push(`${tables.length} table${tables.length === 1 ? "" : "s"} · ${engine} · generated by BalauDeck on ${when.toISOString().slice(0, 10)}`, "");
  L.push("## Tables", "");
  for (const t of tables) L.push(`- [${t.name}](#${anchor(t.name)}) — ${t.columns.length} columns`);
  L.push("");
  for (const t of tables) {
    L.push(`## ${t.name}`, "");
    L.push("| Column | Type | Null | Default | Key | References |", "|---|---|---|---|---|---|");
    for (const c of t.columns) {
      L.push(
        `| ${mdCode(c.name)} | ${mdCell(c.type)} | ${c.nullable ? "yes" : "no"} | ${mdCell(c.def)} | ${c.key} | ${c.refs ? mdCell(c.refs) : ""} |`,
      );
    }
    L.push("");
    if (t.fks.length) {
      L.push("**Foreign keys**", "");
      for (const f of t.fks) {
        L.push(`- ${f.name ? mdCode(f.name) + ": " : ""}${mdCode(f.cols)} → ${mdCode(f.ref)}${f.rules ? ` (${f.rules})` : ""}`);
      }
      L.push("");
    }
    if (t.indexes.length) {
      L.push("**Indexes**", "");
      for (const x of t.indexes) L.push(`- ${mdCode(x.name)}${x.unique ? " (unique)" : ""}: ${mdCell(x.cols)}`);
      L.push("");
    }
    if (t.referencedBy.length) {
      L.push(`**Referenced by:** ${t.referencedBy.map((r) => `[${r}](#${anchor(r)})`).join(", ")}`, "");
    }
  }
  return L.join("\n");
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

export function buildSchemaHtml(
  db: string,
  engine: string,
  names: string[],
  schemas: Map<string, TableSchemaInfo>,
  edges: DocEdge[],
  when = new Date(),
): string {
  const tables = docModel(names, schemas, edges);
  const id = (s: string) => "t-" + anchor(s);
  const parts: string[] = [];
  parts.push(`<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(db || "Database")} — schema</title>
<style>
:root{--bg:#fff;--fg:#1d2329;--mut:#66707a;--line:#dde2e7;--head:#f4f6f8;--acc:#0f8f82}
@media (prefers-color-scheme:dark){:root{--bg:#14181c;--fg:#e4e8ec;--mut:#8d98a3;--line:#2b333b;--head:#1c2227;--acc:#3cc4b4}}
body{margin:0;background:var(--bg);color:var(--fg);font:14px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}
main{max-width:1100px;margin:0 auto;padding:32px 16px 64px}
h1{margin:0 0 4px;font-size:26px}h2{margin:40px 0 10px;font-size:19px;scroll-margin-top:16px}
.meta{color:var(--mut);margin-bottom:24px}
a{color:var(--acc);text-decoration:none}a:hover{text-decoration:underline}
nav ul{columns:3 220px;padding-left:18px}
.wrap{overflow-x:auto}
table{border-collapse:collapse;width:100%;font-size:13px}
th,td{border:1px solid var(--line);padding:5px 8px;text-align:left;vertical-align:top}
th{background:var(--head);font-weight:600}
code,td.c{font-family:ui-monospace,SFMono-Regular,Menlo,monospace;font-size:12.5px}
.k{font-weight:600;color:var(--acc)}.mut{color:var(--mut)}
h3{font-size:14px;margin:14px 0 4px}ul.l{margin:4px 0;padding-left:18px}
</style></head><body><main>`);
  parts.push(`<h1>${esc(db || "Database")}</h1>`);
  parts.push(
    `<div class="meta">${tables.length} table${tables.length === 1 ? "" : "s"} · ${esc(engine)} · generated by BalauDeck on ${when.toISOString().slice(0, 10)}</div>`,
  );
  parts.push(`<nav><ul>${tables.map((t) => `<li><a href="#${id(t.name)}">${esc(t.name)}</a> <span class="mut">${t.columns.length}</span></li>`).join("")}</ul></nav>`);
  for (const t of tables) {
    parts.push(`<h2 id="${id(t.name)}">${esc(t.name)}</h2>`);
    parts.push(`<div class="wrap"><table><thead><tr><th>Column</th><th>Type</th><th>Null</th><th>Default</th><th>Key</th><th>References</th></tr></thead><tbody>`);
    for (const c of t.columns) {
      const [rt] = c.refs.split(/\.(?=[^.]*$)/);
      parts.push(
        `<tr><td class="c">${esc(c.name)}</td><td class="c">${esc(c.type)}</td><td>${c.nullable ? "yes" : "no"}</td><td class="c">${esc(c.def)}</td><td class="k">${esc(c.key)}</td><td class="c">${
          c.refs ? (tables.some((x) => x.name === rt) ? `<a href="#${id(rt)}">${esc(c.refs)}</a>` : esc(c.refs)) : ""
        }</td></tr>`,
      );
    }
    parts.push(`</tbody></table></div>`);
    if (t.fks.length) {
      parts.push(`<h3>Foreign keys</h3><ul class="l">`);
      for (const f of t.fks)
        parts.push(`<li>${f.name ? `<code>${esc(f.name)}</code>: ` : ""}<code>${esc(f.cols)}</code> → <code>${esc(f.ref)}</code>${f.rules ? ` <span class="mut">(${esc(f.rules)})</span>` : ""}</li>`);
      parts.push(`</ul>`);
    }
    if (t.indexes.length) {
      parts.push(`<h3>Indexes</h3><ul class="l">`);
      for (const x of t.indexes) parts.push(`<li><code>${esc(x.name)}</code>${x.unique ? " (unique)" : ""}: <code>${esc(x.cols)}</code></li>`);
      parts.push(`</ul>`);
    }
    if (t.referencedBy.length) {
      parts.push(`<h3>Referenced by</h3><p>${t.referencedBy.map((r) => `<a href="#${id(r)}">${esc(r)}</a>`).join(", ")}</p>`);
    }
  }
  parts.push(`</main></body></html>`);
  return parts.join("\n");
}
